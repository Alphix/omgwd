"""Turn the compiled BPF object into a C header for omgwd's bare-bones loader.

usage: bpf2c.py OBJ SECTION MAP OUT.h PREFIX

Emits PREFIX_insns[] (the instructions of SECTION, as 64-bit words; the
object's byte order is the target's, so the words are read in that order) and PREFIX_map_relocs[] (instruction indices of the ld_imm64 that
reference MAP; the loader patches the map fd into them). Fails on anything
the loader can't handle: other relocations (BPF-to-BPF calls, .rodata,
.data, other maps) or a missing section. No dependencies (ELF64 parsing,
either byte order: bpfel and bpfeb objects).
"""
import struct
import sys

SHT_SYMTAB, SHT_REL = 2, 9
R_BPF_64_64 = 1


def fail(msg):
    sys.exit(f'bpf2c: {msg}')


def main():
    obj, sec_name, map_name, out, prefix = sys.argv[1:6]
    data = open(obj, 'rb').read()
    if data[:4] != b'\x7fELF' or data[4] != 2 or data[5] not in (1, 2):
        fail('not a 64-bit ELF file')
    e = '<' if data[5] == 1 else '>'
    e_shoff, = struct.unpack_from(e + 'Q', data, 0x28)
    e_shentsize, e_shnum, e_shstrndx = struct.unpack_from(e + 'HHH', data, 0x3a)

    secs = []
    for i in range(e_shnum):
        name, typ, _flags, _addr, off, size, link, info, _align, entsize = \
            struct.unpack_from(e + 'IIQQQQIIQQ', data, e_shoff + i * e_shentsize)
        secs.append(dict(name=name, type=typ, off=off, size=size, link=link, info=info,
                         entsize=entsize))
    shstr = secs[e_shstrndx]

    def sname(off, strsec):
        s = strsec['off'] + off
        return data[s:data.index(b'\0', s)].decode()

    for s in secs:
        s['sname'] = sname(s['name'], shstr)
    idx = next((i for i, s in enumerate(secs) if s['sname'] == sec_name), None)
    if idx is None:
        fail(f'no section {sec_name}')
    prog = secs[idx]
    if prog['size'] % 8:
        fail('section size is not a multiple of 8')
    insns = struct.unpack_from(f'{e}{prog["size"] // 8}Q', data, prog['off'])

    relocs = []
    for s in secs:
        if s['type'] != SHT_REL or s['info'] != idx:
            continue
        symtab = secs[s['link']]
        strtab = secs[symtab['link']]
        for k in range(s['size'] // 16):
            r_off, r_info = struct.unpack_from(e + 'QQ', data, s['off'] + k * 16)
            sym, typ = r_info >> 32, r_info & 0xffffffff
            st_name, = struct.unpack_from(e + 'I', data, symtab['off'] + sym * symtab['entsize'])
            name = sname(st_name, strtab)
            if typ != R_BPF_64_64 or name != map_name:
                fail(f'unsupported relocation at {r_off:#x}: type {typ} to "{name}" '
                     f'(only ld_imm64 references to the map "{map_name}" are allowed: '
                     'inline all functions, no .rodata/.data)')
            if r_off % 8:
                fail('misaligned relocation')
            relocs.append(r_off // 8)
    if not relocs:
        fail(f'no reference to the map "{map_name}"')

    with open(out, 'w') as f:
        f.write(f'/* generated by tools/bpf2c.py from {sec_name} of {obj.split("/")[-1]}: do not edit */\n')
        f.write('#include <stdint.h>\n\n')
        f.write(f'static const uint64_t {prefix}_insns[] = {{\n')
        for i in range(0, len(insns), 4):
            f.write('\t' + ' '.join(f'0x{x:016x}ULL,' for x in insns[i:i + 4]) + '\n')
        f.write('};\n\n')
        f.write(f'static const unsigned int {prefix}_map_relocs[] = {{ '
                + ', '.join(str(r) for r in relocs) + ' };\n')


if __name__ == '__main__':
    main()
